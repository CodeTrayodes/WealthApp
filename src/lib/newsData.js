// Helper function to get news by category
export const getNewsByCategory = (category) => {
  return mockNewsData.filter(news => news.category === category);
};

// Helper function to search news
export const searchNews = (query) => {
  if (!query) return mockNewsData;
  
  const searchTerm = query.toLowerCase();
  return mockNewsData.filter(news => 
    news.title.toLowerCase().includes(searchTerm) ||
    news.summary.toLowerCase().includes(searchTerm) ||
    news.tags.some(tag => tag.toLowerCase().includes(searchTerm)) ||
    news.category.toLowerCase().includes(searchTerm)
  );
};

// Helper function to get news by impact
export const getNewsByImpact = (impact) => {
  return mockNewsData.filter(news => news.impact === impact);
};

// Helper function to get trending news (high relevance score)
export const getTrendingNews = () => {
  return mockNewsData
    .filter(news => news.relevanceScore >= 85)
    .sort((a, b) => b.relevanceScore - a.relevanceScore);
};